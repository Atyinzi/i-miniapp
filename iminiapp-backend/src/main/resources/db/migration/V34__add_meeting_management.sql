-- 会议预订阶段 1：会议室基础资料、开放时段、阶梯价格与配套服务。
CREATE TABLE bf_meeting_room (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    room_code VARCHAR(50) NOT NULL,
    name VARCHAR(120) NOT NULL,
    location VARCHAR(255) NOT NULL,
    capacity INT NOT NULL,
    description TEXT,
    open_time TIME NOT NULL,
    close_time TIME NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_meeting_room_code (room_code),
    INDEX idx_meeting_room_status_capacity (status, capacity),
    CONSTRAINT fk_meeting_room_created_by FOREIGN KEY (created_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT fk_meeting_room_updated_by FOREIGN KEY (updated_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_meeting_room_capacity CHECK (capacity BETWEEN 1 AND 100000),
    CONSTRAINT chk_meeting_room_hours CHECK (open_time < close_time),
    CONSTRAINT chk_meeting_room_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会议室';

CREATE TABLE bf_meeting_room_equipment (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    room_id BIGINT NOT NULL,
    equipment_code VARCHAR(50) NOT NULL,
    name VARCHAR(120) NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    description VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_meeting_equipment_room_code (room_id, equipment_code),
    INDEX idx_meeting_equipment_room_status (room_id, status),
    CONSTRAINT fk_meeting_equipment_room FOREIGN KEY (room_id) REFERENCES bf_meeting_room(id),
    CONSTRAINT fk_meeting_equipment_created_by FOREIGN KEY (created_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT fk_meeting_equipment_updated_by FOREIGN KEY (updated_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_meeting_equipment_quantity CHECK (quantity BETWEEN 1 AND 100000),
    CONSTRAINT chk_meeting_equipment_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会议室固定设备';

CREATE TABLE bf_meeting_opening_rule (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    room_id BIGINT NOT NULL,
    day_of_week TINYINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    slot_minutes INT NOT NULL DEFAULT 30,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_meeting_opening_range (room_id, day_of_week, start_time, end_time),
    INDEX idx_meeting_opening_room_day (room_id, day_of_week, status),
    CONSTRAINT fk_meeting_opening_room FOREIGN KEY (room_id) REFERENCES bf_meeting_room(id),
    CONSTRAINT fk_meeting_opening_created_by FOREIGN KEY (created_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT fk_meeting_opening_updated_by FOREIGN KEY (updated_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_meeting_opening_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT chk_meeting_opening_time CHECK (start_time < end_time),
    CONSTRAINT chk_meeting_opening_slot CHECK (slot_minutes BETWEEN 15 AND 720),
    CONSTRAINT chk_meeting_opening_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会议室每周可预订时段';

CREATE TABLE bf_meeting_price_rule (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    room_id BIGINT NOT NULL,
    rule_code VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    start_date DATE NULL,
    end_date DATE NULL,
    day_of_week TINYINT NULL,
    start_time TIME NULL,
    end_time TIME NULL,
    min_attendees INT NULL,
    max_attendees INT NULL,
    price_cent BIGINT NOT NULL,
    priority INT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_meeting_price_rule_code (rule_code),
    INDEX idx_meeting_price_rule_match (room_id, status, priority, day_of_week),
    INDEX idx_meeting_price_rule_date (room_id, start_date, end_date),
    CONSTRAINT fk_meeting_price_room FOREIGN KEY (room_id) REFERENCES bf_meeting_room(id),
    CONSTRAINT fk_meeting_price_created_by FOREIGN KEY (created_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT fk_meeting_price_updated_by FOREIGN KEY (updated_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_meeting_price_amount CHECK (price_cent >= 0),
    CONSTRAINT chk_meeting_price_dates CHECK (start_date IS NULL OR end_date IS NULL OR start_date <= end_date),
    CONSTRAINT chk_meeting_price_day CHECK (day_of_week IS NULL OR day_of_week BETWEEN 1 AND 7),
    CONSTRAINT chk_meeting_price_times CHECK ((start_time IS NULL AND end_time IS NULL) OR (start_time IS NOT NULL AND end_time IS NOT NULL AND start_time < end_time)),
    CONSTRAINT chk_meeting_price_attendees CHECK ((min_attendees IS NULL AND max_attendees IS NULL) OR (min_attendees IS NOT NULL AND max_attendees IS NOT NULL AND min_attendees >= 1 AND min_attendees <= max_attendees)),
    CONSTRAINT chk_meeting_price_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会议室按时段和参会规模收费规则';

CREATE TABLE bf_meeting_service (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    service_code VARCHAR(50) NOT NULL,
    name VARCHAR(120) NOT NULL,
    service_type VARCHAR(20) NOT NULL,
    pricing_unit VARCHAR(20) NOT NULL,
    price_cent BIGINT NOT NULL,
    description VARCHAR(1000),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_meeting_service_code (service_code),
    INDEX idx_meeting_service_type_status (service_type, status),
    CONSTRAINT fk_meeting_service_created_by FOREIGN KEY (created_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT fk_meeting_service_updated_by FOREIGN KEY (updated_by) REFERENCES bf_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_meeting_service_type CHECK (service_type IN ('EQUIPMENT', 'TEA_BREAK', 'ACCOMMODATION')),
    CONSTRAINT chk_meeting_service_unit CHECK (pricing_unit IN ('PER_EVENT', 'PER_PERSON', 'PER_HOUR', 'PER_DAY')),
    CONSTRAINT chk_meeting_service_price CHECK (price_cent >= 0),
    CONSTRAINT chk_meeting_service_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会议配套服务';
